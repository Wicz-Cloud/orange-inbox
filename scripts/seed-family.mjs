#!/usr/bin/env node
// Idempotent family mailbox seeder. Reads family.json (gitignored, see
// family.example.json) and creates, per person: a users row and a mailbox.
// Kids get a 'member' grant on their own mailbox only; admins (users.is_admin)
// get 'owner' on every mailbox so the unified inbox shows everything. Mirrors what
// POST /api/mailboxes and /api/mailboxes/:id/members write, so the in-app
// UI keeps working on the result.
//
// Per-person "allow": ["nana@example.com", "@school.org"] sets that kid's
// inbound allowlist (kids only); other senders land in the admin-only held@ mailbox.
//
// Usage: node scripts/seed-family.mjs [--print | --local | --remote]
//   --print   write the SQL to stdout only (default)
//   --local   apply to the local D1 (wrangler dev state)
//   --remote  apply to the production D1
// The domain must already exist (add it in the app first).

import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mode = process.argv[2] ?? "--print";
if (!["--print", "--local", "--remote"].includes(mode)) {
  console.error("usage: seed-family.mjs [--print|--local|--remote]");
  process.exit(1);
}

const cfg = JSON.parse(readFileSync(join(root, "family.json"), "utf8"));
const LOCAL = /^[a-z0-9._+-]+$/;
const EMAIL = /^[a-z0-9._+-]+@[a-z0-9.-]+\.[a-z]{2,}$/;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const norm = (s) => String(s).trim().toLowerCase();

const domain = norm(cfg.domain);
const admin = norm(cfg.admin); // primary admin; owns the catch-all, no mailbox of their own here
if (!/^[a-z0-9.-]+\.[a-z]{2,}$/.test(domain)) throw new Error(`bad domain: ${domain}`);
if (!EMAIL.test(admin)) throw new Error(`bad admin email: ${admin}`);

const uuid = "lower(hex(randomblob(4))||'-'||hex(randomblob(2))||'-4'||substr(hex(randomblob(2)),2)||'-a'||substr(hex(randomblob(2)),2)||'-'||hex(randomblob(6)))";
const dom = `(SELECT id FROM domains WHERE name = ${q(domain)})`;
const grant = (email, lp, role) =>
  `INSERT INTO user_mailbox_access (user_id, mailbox_id, role) SELECT u.id, m.id, ${q(role)} FROM users u, mailboxes m WHERE u.email = ${q(email)} AND m.domain_id = ${dom} AND m.local_part = ${q(lp)} ON CONFLICT(user_id, mailbox_id) DO UPDATE SET role = excluded.role;`;

// people: { local_part, display_name?, email?, role: "admin" | "kid" }
const people = cfg.people.map((p) => {
  const lp = norm(p.local_part);
  const email = norm(p.email ?? `${lp}@${domain}`);
  if (!LOCAL.test(lp)) throw new Error(`bad local_part: ${lp}`);
  if (!EMAIL.test(email)) throw new Error(`bad email: ${email}`);
  if (!["admin", "kid"].includes(p.role)) throw new Error(`bad role for ${lp}: ${p.role}`);
  return { lp, email, role: p.role, allow: (p.allow ?? []).map(norm), name: p.display_name ?? lp[0].toUpperCase() + lp.slice(1) };
});

const sql = [`-- generated by scripts/seed-family.mjs for ${domain}`];
for (const p of people) {
  sql.push(
    `INSERT INTO users (id, email, display_name) SELECT ${uuid}, ${q(p.email)}, ${q(p.name)} WHERE NOT EXISTS (SELECT 1 FROM users WHERE email = ${q(p.email)});`,
    `INSERT INTO mailboxes (id, domain_id, local_part, display_name, is_catch_all) SELECT ${uuid}, ${dom}, ${q(p.lp)}, ${q(p.name)}, 0 WHERE ${dom} IS NOT NULL AND NOT EXISTS (SELECT 1 FROM mailboxes WHERE domain_id = ${dom} AND local_part = ${q(p.lp)});`,
  );
  if (p.role === "admin") sql.push(`UPDATE users SET is_admin = 1 WHERE email = ${q(p.email)};`);
}
// Admin-only collection mailbox for mail from senders a kid hasn't approved.
const HELD = { lp: "held", name: "Held for review" };
sql.push(
  `INSERT INTO mailboxes (id, domain_id, local_part, display_name, is_catch_all) SELECT ${uuid}, ${dom}, ${q(HELD.lp)}, ${q(HELD.name)}, 0 WHERE ${dom} IS NOT NULL AND NOT EXISTS (SELECT 1 FROM mailboxes WHERE domain_id = ${dom} AND local_part = ${q(HELD.lp)});`,
);
for (const p of people.filter((x) => x.role === "kid")) {
  sql.push(`UPDATE mailboxes SET hold_unknown = 1 WHERE domain_id = ${dom} AND local_part = ${q(p.lp)};`);
  for (const pat of p.allow) {
    if (!/^(@[a-z0-9.-]+\.[a-z]{2,}|[a-z0-9._+-]+@[a-z0-9.-]+\.[a-z]{2,})$/.test(pat)) throw new Error(`bad allow pattern: ${pat}`);
    sql.push(
      `INSERT OR IGNORE INTO sender_allowlist (mailbox_id, pattern) SELECT id, ${q(pat)} FROM mailboxes WHERE domain_id = ${dom} AND local_part = ${q(p.lp)};`,
    );
  }
}
const admins = [admin, ...people.filter((p) => p.role === "admin").map((p) => p.email)];
for (const p of people) {
  // Everyone gets access to their own mailbox: kids as 'member' (read/send, no
  // management), admins as 'owner'. Re-running resets the role to this value.
  sql.push(grant(p.email, p.lp, p.role === "admin" ? "owner" : "member"));
  // Every admin owns every person's mailbox so the unified inbox shows all.
  for (const a of new Set(admins)) if (a !== p.email) sql.push(grant(a, p.lp, "owner"));
}
for (const a of new Set(admins)) sql.push(grant(a, HELD.lp, "owner"));

const out = sql.join("\n") + "\n";
if (mode === "--print") {
  process.stdout.write(out);
} else {
  const file = join(mkdtempSync(join(tmpdir(), "seed-family-")), "seed.sql");
  writeFileSync(file, out);
  execFileSync(
    "npx",
    ["wrangler", "d1", "execute", "orange-inbox", mode, "--file", file],
    { cwd: join(root, "web"), stdio: "inherit" },
  );
}
